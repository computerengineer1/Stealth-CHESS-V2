"""
Stealth Chess Helper - Core License Cryptography (Ed25519)
==========================================================
Shared module used by:
  * dev_tools/key_generator.py   (owner only - holds the PRIVATE key)
  * licensing.py                 (Windows client - embeds PUBLIC key only)

KEY SECURITY MODEL
------------------
1. The PRIVATE signing key NEVER ships with any client build.
   It lives only in a file on the owner's PC:  stealth_owner_key.pem
   (git-ignored). If it is lost, no new keys can ever be issued.
2. Clients embed ONLY the public verification key. A cracker who
   extracts it cannot forge a single valid license key.
3. Every key is cryptographically bound to a device HWID and an
   expiry date. Changing one byte invalidates the signature.
4. No "test keys", no shared secrets, no XOR databases.

Key format (human friendly, 5 groups):
    <PREFIX>-<EXP>-<N-N-N>-<SIG(8 hex)>
    PREFIX : MON | TRM | LFT | TRL
    EXP    : days since epoch, 4 hex chars  -> expiry date
    N      : 12 random hex chars (unique serial / nonce)
    SIG    : first 8 hex chars of Ed25519 signature over the
             canonical payload below.

Canonical signed payload (UTF-8):
    SCHL1|<PREFIX>|<EXP>|<NONCE>|<HWID_OR_00000000>
"""

import datetime
import hashlib

try:
    from cryptography.hazmat.primitives.asymmetric.ed25519 import (
        Ed25519PrivateKey,
        Ed25519PublicKey,
    )
    from cryptography.hazmat.primitives import serialization
    from cryptography.exceptions import InvalidSignature
    _CRYPTO_OK = True
except ImportError:  # pragma: no cover
    _CRYPTO_OK = False

# ----------------------------------------------------------------------
# Public verification key — SAFE to ship inside clients.
# This must match the private key generated by make_owner_keys.py.
# ----------------------------------------------------------------------
PUBLIC_KEY_B64 = "f80cfd3191b3d7cb8f6483e97236534fd0479cdb48f40c1e742fc164cf884d05"

VALID_PREFIXES = {"MON", "TRM", "LFT", "TRL"}
UNBOUND_HWID = "00000000"          # wildcard: key may bind on first activation
_TIER_NAMES = {
    "MON": "Monthly",
    "TRM": "3 Months",
    "LFT": "Lifetime",
    "TRL": "Trial",
}


def require_crypto():
    if not _CRYPTO_OK:
        raise RuntimeError(
            "The 'cryptography' package is required for the Ed25519 license system. "
            "Install it with:  pip install cryptography"
        )


def load_private_key(path: str):
    """Owner-only helper: loads the private signing key from disk."""
    require_crypto()
    with open(path, "rb") as f:
        data = f.read()
    try:
        return serialization.load_pem_private_key(data, password=None)
    except ValueError:
        # Try DER
        return serialization.load_der_private_key(data, password=None)


def get_public_key():
    require_crypto()
    raw = bytes.fromhex(PUBLIC_KEY_B64.replace("\n", "").strip()) \
        if _is_hex(PUBLIC_KEY_B64) else None
    if raw is None or len(raw) != 32:
        # Accept base64 form too
        import base64
        raw = base64.b64decode(PUBLIC_KEY_B64.strip())
    return Ed25519PublicKey.from_public_bytes(raw)


def _is_hex(s: str) -> bool:
    try:
        bytes.fromhex(s)
        return True
    except Exception:
        return False


def _public_key_bytes() -> bytes:
    return get_public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )


def public_key_hex() -> str:
    """Hex of the public key — printed into client files by make_owner_keys.py."""
    require_crypto()
    return _public_key_bytes().hex()


def canonical_payload(prefix: str, expd: str, nonce: str, hwid_norm: str) -> bytes:
    return f"SCHL1|{prefix}|{expd}|{nonce}|{hwid_norm}".encode("utf-8")


def normalize_hwid(hwid: str) -> str:
    """Strip separators/whitespace, uppercase. Empty -> wildcard token."""
    if not hwid:
        return UNBOUND_HWID
    cleaned = "".join(ch for ch in hwid.upper() if ch.isalnum())
    return cleaned if cleaned else UNBOUND_HWID


def sign_key(private_key, prefix: str, expd: str, nonce: str, hwid_norm: str) -> str:
    """Produce the 8-hex short signature tag for a key."""
    sig = private_key.sign(canonical_payload(prefix, expd, nonce, hwid_norm))
    return hashlib.sha256(sig).hexdigest()[:8].upper()


def format_key(prefix: str, expd: str, nonce: str, tag: str) -> str:
    """MON-1F2A-ABCD-EF01-2345-9C1D2E3F style grouping."""
    n = nonce.upper()
    return f"{prefix}-{expd}-{n[0:4]}-{n[4:8]}-{n[8:12]}-{tag}"


def parse_key(key: str):
    """Return (prefix, expd, nonce, tag) or None if malformed."""
    parts = key.upper().split("-")
    if len(parts) != 6:
        return None
    prefix, expd, a, b, c, tag = parts
    if prefix not in VALID_PREFIXES:
        return None
    if len(expd) != 4 or len(a) != 4 or len(b) != 4 or len(c) != 4 or len(tag) != 8:
        return None
    nonce = a + b + c
    for chunk in (expd, nonce, tag):
        if not _is_hex(chunk):
            return None
    return prefix, expd, nonce, tag


def key_id(prefix: str, expd: str, nonce: str) -> str:
    """Short public identifier of a key (shown in the owner ledger)."""
    return hashlib.sha256(f"SCHL1|{prefix}|{expd}|{nonce}".encode()).hexdigest()[:10].upper()


def verify_key(key: str, hwid: str = None):
    """
    Cryptographically verify an Ed25519-signed license token OFFLINE using
    ONLY the embedded public key.

    A valid token is:   <KEY-ID-10HEX>.<base64url(payload|sig)>
    where payload = SCHL1|PREFIX|EXP|NONCE|HWID and sig is a full
    Ed25519 signature produced by the owner's private key. It is
    mathematically impossible to forge a token without that private key.

    Returns dict or None.
    """
    require_crypto()
    import base64
    token = (key or "").strip()
    if "." not in token:
        return None
    kid_part, b64_part = token.split(".", 1)
    try:
        pad = "=" * (-len(b64_part) % 4)
        raw = base64.urlsafe_b64decode(b64_part + pad)
        if len(raw) < 66:
            return None
        sig = raw[-64:]
        meta = raw[:-65]           # drop the 0x00 separator too
        parts = meta.decode("utf-8").split("|")
        if len(parts) != 5 or parts[0] != "SCHL1":
            return None
        _, prefix, expd, nonce, hwid_norm = parts
        prefix, expd, nonce = prefix.upper(), expd.upper(), nonce.upper()
        if prefix not in VALID_PREFIXES or len(sig) != 64:
            return None
        # Full asymmetric verification — public key only.
        get_public_key().verify(sig, canonical_payload(prefix, expd, nonce, hwid_norm))
    except Exception:
        return None

    # Optional consistency check against the short human ID.
    if kid_part and len(kid_part) == 10:
        if key_id(prefix, expd, nonce) != kid_part.upper():
            return None

    bound = hwid_norm != UNBOUND_HWID
    if bound:
        current = normalize_hwid(hwid) if hwid else None
        if current is not None and current != hwid_norm:
            return {
                "valid": False, "expired": False, "wrong_device": True,
                "tier": _TIER_NAMES.get(prefix, "Unknown"),
                "expiry_date": "", "is_device_bound": True, "nonce": nonce,
            }

    try:
        epoch_days = int(expd, 16)
    except ValueError:
        return None
    expiry_date = datetime.date(1970, 1, 1) + datetime.timedelta(days=epoch_days)
    expired = datetime.date.today() > expiry_date

    return {
        "valid": not expired,
        "expired": expired,
        "tier": _TIER_NAMES.get(prefix, "Unknown"),
        "expiry_date": expiry_date.strftime("%Y-%m-%d"),
        "is_device_bound": bound,
        "hwid": hwid_norm,
        "nonce": nonce,
    }


# ----------------------------------------------------------------------
# Final verification implementation (defined after helpers above).
# Design note: the printable short key carries a 32-bit tag derived from
# the Ed25519 signature digest keyed by the public key bytes. Only the
# holder of the PRIVATE key can produce matching tags; anyone with just
# the public key still cannot forge them because the tag input includes
# the actual signature (which needs the private key). Verification
# re-computes nothing — instead the SERVER (holding the ledger) confirms
# the tag, and OFFLINE clients validate via the embedded full-signature
# blob produced by `encode_offline_blob()` for air-gapped activations.
# ----------------------------------------------------------------------

def encode_offline_blob(private_key, prefix: str, expd: str, nonce: str, hwid_norm: str) -> str:
    """
    Owner tool: produce the signed activation token for a client.
    This IS what the customer pastes into the app (or what the server returns).
    Framing:  meta_bytes + b"\x00" + 64-byte Ed25519 signature (fixed length).
    """
    import base64
    payload = canonical_payload(prefix, expd, nonce, hwid_norm)
    sig = private_key.sign(payload)
    raw = payload + b"\x00" + sig
    b64 = base64.urlsafe_b64encode(raw).decode().rstrip("=")
    return f"{key_id(prefix, expd, nonce)}.{b64}"


def tag_from_signature(signature: bytes) -> str:
    return hashlib.sha256(signature).hexdigest()[:8].upper()


def issue_key(private_key, tier: str, days: int, hwid: str = "") -> dict:
    """
    Owner-only: generate a complete signed license for a customer.

    Returns {"key": printable_short_id, "token": signed_activation_token,
             "tier": ..., "expiry": ...}
    """
    import secrets
    prefix_map = {"MONTHLY": "MON", "3MONTHS": "TRM", "LIFETIME": "LFT", "TRIAL": "TRL"}
    prefix = prefix_map[tier.upper()]
    if tier.upper() == "LIFETIME":
        expiry = datetime.date(2099, 12, 31)
    else:
        expiry = datetime.date.today() + datetime.timedelta(days=days)
    expd = f"{(expiry - datetime.date(1970, 1, 1)).days:04X}"
    nonce = secrets.token_hex(6).upper()
    hwid_norm = normalize_hwid(hwid)
    token = encode_offline_blob(private_key, prefix, expd, nonce, hwid_norm)
    return {
        "key": key_id(prefix, expd, nonce),
        "token": token,
        "tier": _TIER_NAMES[prefix],
        "expiry": expiry.strftime("%Y-%m-%d"),
        "hwid": hwid_norm,
    }
